export const getResponsive = (width) => {
  // 390px is our base mobile reference.
  // Everything scales gently around it.
  const scale = Math.max(0.82, Math.min(width / 390, 1.08));

  const s = (value) => Math.round(value * scale);

  return {
    scale,

    // --------------------------------------------------------
    // SPACING
    // --------------------------------------------------------

    pagePadding: s(12),
    sectionGap: s(12),
    cardPadding: s(12),
    smallGap: s(6),

    // --------------------------------------------------------
    // FONT SIZES
    // --------------------------------------------------------

    fontXs: s(8),
    fontSm: s(10),
    fontMd: s(12),
    fontLg: s(14),
    fontXl: s(16),
    fontTitle: s(18),
    fontNumber: s(22),

    // --------------------------------------------------------
    // ICONS
    // --------------------------------------------------------

    iconXs: s(12),
    iconSm: s(15),
    iconMd: s(18),
    iconLg: s(22),

    // --------------------------------------------------------
    // RADIUS
    // --------------------------------------------------------

    radiusSm: s(6),
    radiusMd: s(10),
    radiusLg: s(14),

    // --------------------------------------------------------
    // CONTROLS
    // --------------------------------------------------------

    buttonHeight: s(42),
    inputHeight: s(44),

    // --------------------------------------------------------
    // HEADER
    // --------------------------------------------------------

    headerLogo: s(44),
    headerIcon: s(16),
    headerAvatar: s(40),

    // --------------------------------------------------------
    // BOTTOM TAB
    // --------------------------------------------------------

    tabIcon: s(18),
    tabLabel: s(10),
  };
};
